// Real-time suggestions query (fast, responsive)
export async function getSearchSuggestions(query: string): Promise<string[]> {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();

  // Try Google suggest first
  try {
    const res = await fetch(`https://suggestqueries.google.com/complete/search?client=firefox&ds=yt&q=${encodeURIComponent(q)}`, {
      signal: AbortSignal.timeout(1800)
    });
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && Array.isArray(data[1])) {
        return data[1].slice(0, 8);
      }
    }
  } catch (_) {}

  // Fallback: match from local extended catalog
  const matched = EXTENDED_CATALOG
    .filter(t => t.title.toLowerCase().includes(q) || t.artist.toLowerCase().includes(q))
    .map(t => `${t.title} - ${t.artist}`)
    .slice(0, 8);
  return matched;
}

/**
 * Searches YouTube using Google YouTube Data API v3 if API key or token is configured
 */
async function searchWithYouTubeDataApi(query: string): Promise<Track[]> {
  if (typeof window === 'undefined') return [];
  const googleToken = localStorage.getItem('resonate_google_access_token');
  const userApiKey = localStorage.getItem('resonate_youtube_api_key') || (import.meta as any).env?.VITE_YOUTUBE_API_KEY;

  if (!googleToken && !userApiKey) return [];

  let url = `https://www.googleapis.com/youtube/v3/search?part=snippet&type=video&videoCategoryId=10&maxResults=20&q=${encodeURIComponent(query)}`;
  const headers: Record<string, string> = {};

  if (googleToken) {
    headers['Authorization'] = `Bearer ${googleToken}`;
  } else if (userApiKey) {
    url += `&key=${encodeURIComponent(userApiKey)}`;
  }

  try {
    const res = await fetch(url, { headers, signal: AbortSignal.timeout(3500) });
    if (!res.ok) return [];
    const data = await res.json();
    if (!Array.isArray(data.items)) return [];

    return data.items
      .filter((it: any) => it.id?.videoId)
      .map((it: any) => ({
        id: it.id.videoId,
        title: it.snippet?.title || 'Unknown Title',
        artist: it.snippet?.channelTitle || 'Artist',
        album: 'YouTube Music',
        duration: 210,
        thumbnailUrl: it.snippet?.thumbnails?.high?.url || it.snippet?.thumbnails?.medium?.url || `https://img.youtube.com/vi/${it.id.videoId}/0.jpg`,
        youtubeUrl: `https://www.youtube.com/watch?v=${it.id.videoId}`,
        lyrics: `[Enjoy listening to ${it.snippet?.title} on Resonate!]`
      } as Track));
  } catch {
    return [];
  }
}

/**
 * Parses raw YouTube HTML search results or InnerTube JSON string for video IDs
 */
function parseYouTubeSearchResults(raw: string): Track[] {
  const tracks: Track[] = [];
  if (!raw || typeof raw !== 'string' || raw.trim().length === 0) return tracks;

  try {
    let data: any = null;
    const trimmed = raw.trim();
    if (trimmed.startsWith('{')) {
      data = JSON.parse(trimmed);
    } else {
      const startIdx = trimmed.indexOf('ytInitialData');
      if (startIdx !== -1) {
        const firstBrace = trimmed.indexOf('{', startIdx);
        if (firstBrace !== -1) {
          let depth = 0;
          let endIdx = -1;
          let inString = false;
          let escape = false;
          for (let i = firstBrace; i < trimmed.length; i++) {
            const c = trimmed[i];
            if (escape) { escape = false; continue; }
            if (c === '\\') { escape = true; continue; }
            if (c === '"') { inString = !inString; continue; }
            if (!inString) {
              if (c === '{') depth++;
              else if (c === '}') {
                depth--;
                if (depth === 0) {
                  endIdx = i + 1;
                  break;
                }
              }
            }
          }
          if (endIdx !== -1) {
            data = JSON.parse(trimmed.substring(firstBrace, endIdx));
          }
        }
      }
    }
    if (!data) return [];

    const visited = new Set<string>();

    function walk(node: any) {
      if (!node || typeof node !== 'object') return;

      // 1. YouTube Music InnerTube item
      if (node.musicResponsiveListItemRenderer) {
        const item = node.musicResponsiveListItemRenderer;
        const flexColumns = item.flexColumns || [];
        const titleRun = flexColumns[0]?.musicResponsiveListItemFlexColumnRenderer?.text?.runs?.[0];
        const title = titleRun?.text;
        const navEndpoint = titleRun?.navigationEndpoint || item.navigationEndpoint;
        const videoId = navEndpoint?.watchEndpoint?.videoId;
        const artistRuns = flexColumns[1]?.musicResponsiveListItemFlexColumnRenderer?.text?.runs || [];
        const artist = artistRuns.map((r: any) => r.text).join('') || 'YouTube Music';
        const thumbs = item.thumbnail?.musicThumbnailRenderer?.thumbnail?.thumbnails;
        const thumb = thumbs ? thumbs[thumbs.length - 1].url : (videoId ? `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg` : '');

        if (videoId && title && !visited.has(videoId)) {
          visited.add(videoId);
          tracks.push({
            id: videoId,
            title,
            artist,
            album: 'YouTube Music',
            duration: 210,
            thumbnailUrl: thumb,
            youtubeUrl: `https://www.youtube.com/watch?v=${videoId}`,
            lyrics: `[Enjoy listening to ${title} on Resonate!]`
          });
        }
      }

      // 2. Standard YouTube videoRenderer
      if (node.videoRenderer && node.videoRenderer.videoId) {
        const vr = node.videoRenderer;
        if (!visited.has(vr.videoId)) {
          visited.add(vr.videoId);
          const title = vr.title?.runs?.[0]?.text || vr.headline?.simpleText || 'Untitled Song';
          const artist = vr.ownerText?.runs?.[0]?.text || vr.longBylineText?.runs?.[0]?.text || vr.shortBylineText?.runs?.[0]?.text || 'Artist';
          const durationText = vr.lengthText?.simpleText || '3:30';
          const parts = durationText.split(':').map(Number);
          const duration = parts.length === 2 ? parts[0] * 60 + parts[1] : parts.length === 3 ? parts[0] * 3600 + parts[1] * 60 + parts[2] : 210;
          const thumb = vr.thumbnail?.thumbnails?.slice(-1)[0]?.url || `https://i.ytimg.com/vi/${vr.videoId}/hqdefault.jpg`;
          tracks.push({
            id: vr.videoId,
            title,
            artist,
            album: 'YouTube Music',
            duration,
            thumbnailUrl: thumb,
            youtubeUrl: `https://www.youtube.com/watch?v=${vr.videoId}`,
            lyrics: `[Enjoy listening to ${title} on Resonate!]`
          });
        }
      }

      if (Array.isArray(node)) {
        for (const it of node) walk(it);
      } else {
        for (const k of Object.keys(node)) {
          if (k !== 'videoRenderer' && k !== 'musicResponsiveListItemRenderer') {
            walk(node[k]);
          }
        }
      }
    }

    walk(data);
  } catch (_) {}
  return tracks;
}

/**
 * Advanced Multi-Engine Universal YouTube Search
 * 1. Native Android bridge (CORS-free direct connection via MainActivity.kt)
 * 2. Vercel / Vite Serverless API (/api/search)
 * 3. YouTube Data API v3 (if user/admin configured API key)
 * 4. Transparent CORS Gateways & Invidious/Piped Live Mirrors
 * 5. Smart Fuzzy catalog match with weighted token scoring
 */
export async function searchYouTube(query: string): Promise<Track[]> {
  if (!query || query.trim() === '') {
    return EXTENDED_CATALOG.slice(0, 12);
  }

  const cleanQuery = query.trim();

  // 1. Android Native App Bridge (Zero CORS, 100% reliable in APK)
  if (typeof window !== 'undefined' && (window as any).ResonateNative?.searchYouTubeNative) {
    try {
      const rawNative = (window as any).ResonateNative.searchYouTubeNative(cleanQuery);
      if (rawNative && rawNative !== '[]' && rawNative.length > 50) {
        const nativeTracks = parseYouTubeSearchResults(rawNative);
        if (nativeTracks.length > 0) {
          return nativeTracks;
        }
      }
    } catch (e) {
      console.warn('Native search failed, falling back to web endpoints:', e);
    }
  }

  // 2. Vercel Serverless / Vite dev search API (Zero CORS for website & webapp)
  try {
    const apiRes = await fetch(`/api/search?q=${encodeURIComponent(cleanQuery)}`, {
      signal: AbortSignal.timeout(4500)
    });
    if (apiRes.ok) {
      const tracks = await apiRes.json();
      if (Array.isArray(tracks) && tracks.length > 0) {
        return tracks;
      }
    }
  } catch (_) {
    // Continue to external gateways
  }

  // 3. YouTube Data API v3 (if user added key in settings)
  try {
    const apiResults = await searchWithYouTubeDataApi(cleanQuery);
    if (apiResults.length > 0) {
      return apiResults;
    }
  } catch (_) {}

  // 4. Live CORS Gateways for YouTube HTML
  const corsGateways = [
    `https://corsproxy.io/?url=${encodeURIComponent(`https://www.youtube.com/results?search_query=${encodeURIComponent(cleanQuery)}`)}`,
    `https://api.allorigins.win/raw?url=${encodeURIComponent(`https://www.youtube.com/results?search_query=${encodeURIComponent(cleanQuery)}`)}`,
    `https://api.codetabs.com/v1/proxy?quest=${encodeURIComponent(`https://www.youtube.com/results?search_query=${encodeURIComponent(cleanQuery)}`)}`,
  ];

  for (const gwUrl of corsGateways) {
    try {
      const res = await fetch(gwUrl, { signal: AbortSignal.timeout(3500) });
      if (res.ok) {
        const text = await res.text();
        const parsed = parseYouTubeSearchResults(text);
        if (parsed.length > 0) {
          return parsed;
        }
      }
    } catch (_) {}
  }

  // 5. Invidious & Piped public mirrors in parallel
  const searchEndpoints = [
    {
      url: `https://pipedapi.tokhmi.xyz/search?q=${encodeURIComponent(cleanQuery)}&filter=music_songs`,
      parse: (data: any) => (data.items || data || [])
        .filter((it: any) => it.url || it.id)
        .slice(0, 15)
        .map((item: any) => {
          const vidId = (item.url ? item.url.replace('/watch?v=', '') : item.id) || '';
          return {
            id: vidId || `yt-${Math.random().toString(36).substring(7)}`,
            title: item.title || 'Untitled Song',
            artist: item.uploaderName || item.artist || 'Artist',
            album: item.album || 'YouTube Music',
            duration: item.duration || 210,
            thumbnailUrl: item.thumbnail || `https://img.youtube.com/vi/${vidId}/hqdefault.jpg`,
            youtubeUrl: `https://www.youtube.com/watch?v=${vidId}`,
            lyrics: `[Enjoy listening to ${item.title} on Resonate!]`
          } as Track;
        })
    },
    {
      url: `https://vid.puffyan.us/api/v1/search?q=${encodeURIComponent(cleanQuery)}&type=video`,
      parse: (data: any) => (Array.isArray(data) ? data : [])
        .filter((it: any) => it.videoId)
        .slice(0, 15)
        .map((item: any) => ({
          id: item.videoId,
          title: item.title || 'Untitled Song',
          artist: item.author || 'Artist',
          album: 'YouTube Music',
          duration: item.lengthSeconds || 210,
          thumbnailUrl: item.videoThumbnails?.[0]?.url || `https://img.youtube.com/vi/${item.videoId}/hqdefault.jpg`,
          youtubeUrl: `https://www.youtube.com/watch?v=${item.videoId}`,
          lyrics: `[Enjoy listening to ${item.title} on Resonate!]`
        } as Track))
    },
  ];

  try {
    const remotePromise = Promise.any(
      searchEndpoints.map(async (ep) => {
        const res = await fetch(ep.url, { signal: AbortSignal.timeout(3200) });
        if (!res.ok) throw new Error('Endpoint failed');
        const data = await res.json();
        const parsed = ep.parse(data);
        if (!parsed || parsed.length === 0) throw new Error('No items');
        return parsed;
      })
    );
    const remoteResults = (await remotePromise) as Track[];
    if (remoteResults && remoteResults.length > 0) {
      return remoteResults;
    }
  } catch (_) {}

  // 6. Global Music Metadata Search (iTunes Music API - 100% CORS-friendly worldwide)
  try {
    const itunesRes = await fetch(`https://itunes.apple.com/search?term=${encodeURIComponent(cleanQuery)}&media=music&entity=song&limit=15`, {
      signal: AbortSignal.timeout(2800)
    });
    if (itunesRes.ok) {
      const data = await itunesRes.json();
      if (Array.isArray(data.results) && data.results.length > 0) {
        const itunesTracks: Track[] = data.results.map((r: any) => {
          // If we have a catalog match for videoId, use that; otherwise generate a clean track ID
          const match = EXTENDED_CATALOG.find(t => 
            t.title.toLowerCase().includes(r.trackName.toLowerCase()) || 
            r.trackName.toLowerCase().includes(t.title.toLowerCase())
          );
          const vidId = match?.id || `itunes-${r.trackId}`;
          const artwork = (r.artworkUrl100 || '').replace('100x100bb', '600x600bb');
          return {
            id: vidId,
            title: r.trackName || 'Untitled Song',
            artist: r.artistName || 'Artist',
            album: r.collectionName || 'Single',
            duration: Math.round((r.trackTimeMillis || 210000) / 1000),
            thumbnailUrl: artwork || `https://img.youtube.com/vi/${vidId}/hqdefault.jpg`,
            youtubeUrl: match ? `https://www.youtube.com/watch?v=${match.id}` : `https://www.youtube.com/results?search_query=${encodeURIComponent(r.trackName + ' ' + r.artistName)}`,
            lyrics: `[Enjoy listening to ${r.trackName} by ${r.artistName} on Resonate!]`
          };
        });
        if (itunesTracks.length > 0) {
          return itunesTracks;
        }
      }
    }
  } catch (_) {}

  // 7. Smart Fuzzy Fallback: Score against extended verified catalog
  const cleanTokens = cleanQuery.toLowerCase().replace(/[-–—]/g, ' ').split(/\s+/).filter(Boolean);
  const scoredCatalog = EXTENDED_CATALOG.map((track) => {
    const text = `${track.title} ${track.artist} ${track.album || ''}`.toLowerCase();
    let score = 0;
    for (const token of cleanTokens) {
      if (text.includes(token)) score += 1;
    }
    return { track, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.track);

  return scoredCatalog;
}
